import 'dart:ui';

import 'package:bonfire/map/pixel_tileset/pixel_palette.dart';

/// A pixel art image described entirely in code, as a grid of palette codes.
///
/// Each element of [rows] is a single "pixel row": one character per pixel.
/// All rows must have the same length. The character `'.'` means
/// "transparent" unless it is explicitly present in the [PixelPalette] used
/// to paint this art.
///
/// This is the building block used by [PixelTile]/[PixelTileset] to generate
/// tile images at runtime, without loading any image asset. It is designed
/// to be easy to read and write by hand (or to be generated by an AI agent),
/// much like ASCII art:
///
/// ```dart
/// final grass = PixelArt.rows([
///   'gggggggg',
///   'gGggggGg',
///   'gggggggg',
///   'gggGgggg',
///   'gggggggg',
///   'ggggggGg',
///   'gggggggg',
///   'gggggggg',
/// ]);
/// ```
class PixelArt {
  /// The pixel rows, top to bottom. `rows[y][x]` is the palette code of the
  /// pixel at column `x`, row `y`.
  final List<String> rows;

  /// Width of this art, in pixels (number of characters per row).
  final int width;

  /// Height of this art, in pixels (number of rows).
  final int height;

  PixelArt._(this.rows)
      : width = rows.first.length,
        height = rows.length;

  /// Creates a [PixelArt] from a list of equal-length strings.
  ///
  /// Throws an [ArgumentError] if [rows] is empty or if the rows don't all
  /// have the same length - this is meant to surface typos early (useful
  /// both for humans and for AI agents iterating on pixel art in code).
  factory PixelArt.rows(List<String> rows) {
    if (rows.isEmpty) {
      throw ArgumentError('PixelArt.rows: `rows` cannot be empty.');
    }
    final width = rows.first.length;
    for (var y = 0; y < rows.length; y++) {
      if (rows[y].length != width) {
        throw ArgumentError(
          'PixelArt.rows: all rows must have the same length. '
          'Row 0 has length $width but row $y ("${rows[y]}") '
          'has length ${rows[y].length}.',
        );
      }
    }
    return PixelArt._(rows);
  }

  /// Paints this pixel art onto [canvas], with its top-left pixel at
  /// [offset], resolving each pixel code through [palette].
  ///
  /// [ownerName] is used only to produce a helpful error message pointing at
  /// which tile/frame contains the offending pixel code.
  void paint(
    Canvas canvas,
    Offset offset,
    PixelPalette palette, {
    required String ownerName,
  }) {
    final pixelPaint = Paint()..isAntiAlias = false;
    for (var y = 0; y < height; y++) {
      final row = rows[y];
      for (var x = 0; x < width; x++) {
        final code = row[x];
        final color = palette[code] ?? (code == '.' ? null : _unknownCode(
              code,
              ownerName,
              y,
              x,
              palette,
            ));
        if (color == null || color.a == 0) {
          continue;
        }
        pixelPaint.color = color;
        canvas.drawRect(
          Rect.fromLTWH(offset.dx + x, offset.dy + y, 1, 1),
          pixelPaint,
        );
      }
    }
  }

  Never _unknownCode(
    String code,
    String ownerName,
    int row,
    int column,
    PixelPalette palette,
  ) {
    throw ArgumentError(
      'Unknown pixel code "$code" in "$ownerName" at row $row, column '
      '$column. Known codes: ${palette.keys.join(', ')} '
      '(and "." for transparent).',
    );
  }
}
